#!/usr/bin/env python3
"""
Generate the preview pages.

Each page's own content lives in src/<slug>.html, whose first line is an HTML comment carrying
its <title> and meta description. The chrome around it (the unofficial ribbon, the Athletic
Center masthead and menu, the strip linking every page in this preview, the footer) is the same
on every page, so it lives here. Calendars are written as {{cal:<key>}} and filled from EMBEDS.
Run `python3 build.py` and commit the HTML it writes.
"""

import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
SITE = "https://comfit.smccd.edu"
JOIN = "https://www.ourclublogin.com/login/500092"
LOGO = SITE + "/wp-content/uploads/2023/09/csm-ac-logo-white-notag-1-e1695329298306.png"

# Pool Relay public calendars (share tokens).
EMBEDS = {
    "lanes":   ("gvUr6I1OQGUIk2UtCtcRbE", "Lane by lane, one day"),
    "week":    ("HwsRvPrDRIG35A0tKDcNuN", "Both pools, the whole week"),
    "lap":     ("WaFSqUVBW2gQpy3ePTq8YL", "Lap swim lanes this week"),
    "masters": ("UZhdsQ6PG1FQFNfqnd4g2r", "San Mateo Masters practices"),
    "club":    ("0qZMK1UwYNopjAjBXJMM1h", "Bulldog Swim Club practices"),
    "school":  ("qlSFalluTlPpu7XVhBJwpY", "Bulldogs Swim School lessons"),
}

# Every page in this preview: (file, label, the page it replicates)
PAGES = [
    ("index.html",               "Aquatics",              "/aquatics/"),
    ("pool-schedule.html",       "Pool Schedule",         "/wp-content/uploads/2026/09/9.11Lane-Availability-Sheet-Fall-Sem.pdf"),
    ("bulldogs-swim-school.html", "Bulldogs Swim School", "/aquatics/bulldogs-swim-school/"),
    ("bulldog-swim-club.html",   "Bulldog Swim Club",     "/aquatics/bulldog-swim-club/"),
]
ORIGIN = {f: SITE + path for f, _, path in PAGES}
EXT = 'target="_blank" rel="noopener noreferrer"'


def cal(m):
    token, label = EMBEDS[m.group(1)]
    return (f'<div class="frame"><iframe src="https://www.poolrelay.com/embed/{token}" '
            f'title="CSM Athletic Center: {label}" loading="lazy"></iframe></div>')


def shell(slug, title, description, body):
    origin = ORIGIN[slug]
    on = ' class="on" aria-current="page"'
    strip = "\n".join(f'    <a href="{f}"{on if f == slug else ""}>{label}</a>' for f, label, _ in PAGES)
    return f"""<!doctype html>
<!--
  UNOFFICIAL PREVIEW. Not a College of San Mateo website.
  A replica of {origin}
  Generated by build.py from src/{slug} &mdash; edit those, not this file.
-->
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<meta name="robots" content="noindex, nofollow">
<title>{title}</title>
<meta name="description" content="{description}">
<link rel="preconnect" href="https://fonts.googleapis.com">
<link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>
<link rel="stylesheet" href="https://fonts.googleapis.com/css2?family=Poppins:wght@300;400;600;700&display=swap">
<link rel="stylesheet" href="site.css">
</head>
<body>

<div class="preview-note">
  <b>Unofficial preview.</b> Not a College of San Mateo page &mdash; a mock-up of
  <a href="{origin}" {EXT}>comfit.smccd.edu</a>
  with its pool schedules shown as live Pool Relay calendars. Built by
  <a href="https://www.poolrelay.com" {EXT}>Pool Relay</a>.
</div>

<header class="site">
  <div class="in">
    <a class="logo" href="index.html"><img src="{LOGO}" alt="College of San Mateo Athletic Center"></a>
    <nav class="site">
      <a href="{SITE}/membership/" {EXT}>Membership</a>
      <a class="join" href="{JOIN}" {EXT}>Join Online</a>
      <a href="{SITE}/fitness/" {EXT}>Fitness</a>
      <a class="here" href="index.html">Aquatics</a>
      <a href="{SITE}/group-exercise/" {EXT}>Group Exercise</a>
      <a href="{SITE}/pilates/" {EXT}>Pilates</a>
      <a href="{SITE}/about/" {EXT}>About</a>
      <a href="{SITE}/contact-us/" {EXT}>Contact Us</a>
    </nav>
  </div>
  <nav class="strip" aria-label="Pages in this preview">
{strip}
  </nav>
</header>

{body.strip()}

<footer class="site">
  <div class="in">
    <div>
      <b>College of San Mateo Athletic Center</b>
      Health and Wellness Building 5<br>
      1700 W. Hillsdale Blvd., San Mateo, CA 94402
    </div>
    <div>
      <b>Aquatics Office</b>
      (650) 378-7383<br>
      bulldogs.ss@smccd.edu
    </div>
    <div>
      <b>Membership hours</b>
      Monday – Friday 6:00 a.m. – 8:30 p.m.<br>
      Saturday &amp; Sunday 7:00 a.m. – 5:30 p.m.
    </div>
  </div>
  <p class="fine">This page is an unofficial preview built to demonstrate embedded
    <a href="https://www.poolrelay.com" {EXT}>Pool Relay</a> calendars. It is not operated by or
    affiliated with the College of San Mateo or the San Mateo County Community College District.
    For official schedules see <a href="{SITE}/aquatics/" {EXT}>comfit.smccd.edu</a>.</p>
</footer>

</body>
</html>
"""


def main():
    for slug, _, _ in PAGES:
        src = open(os.path.join(HERE, "src", slug), encoding="utf-8").read()
        m = re.match(r"\s*<!--\s*title:\s*(.*?)\n\s*description:\s*(.*?)\s*-->\s*", src, re.S)
        if not m:
            raise SystemExit(f"src/{slug}: first line must be the title/description comment")
        body = re.sub(r"\{\{cal:(\w+)\}\}", cal, src[m.end():])
        open(os.path.join(HERE, slug), "w", encoding="utf-8").write(shell(slug, m.group(1).strip(), m.group(2).strip(), body))
        print("wrote", slug)


if __name__ == "__main__":
    main()
